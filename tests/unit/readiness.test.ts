import assert from 'node:assert/strict';
import { buildPharmacyIntelligenceReport } from '../../src/lib/pharmacy-intelligence';
import { parseNutritionFacts } from '../../scripts/lib/nutrition-parser';
import { getVerifiedNutritionFacts } from '../../src/lib/wiki-nutrition';
import { detectAdditives } from '../../scripts/lib/additive-keywords';
import { isSafeCrawlerQuery } from '../../src/proxy';

const pharmacy = { hpid: 'C1402250', name: '검증약국', address: '서울 중구', operating_hours: { mon: {open:'0900',close:'2000'}, sat: {open:null,close:null} } };
const report = buildPharmacyIntelligenceReport(pharmacy, {matched:true,votedUserCount:2,votedKeywords:[{label:'친절해요',count:8}], visitorReviewCount:100});
assert.equal(report.keywordAnalysis.topKeywords.length, 0, 'unlicensed/unattributed reviews must not be published');
assert.deepEqual(report.peerComparison.metrics, [], 'no synthetic regional benchmark');
assert.doesNotMatch(JSON.stringify(report), /정기 휴무|30%|20시 이후 야간 운영|평일 하루 평균 9시간|접근성이 우수/);
assert.match(report.visitGuide.regularClosedSummary, /확인/);
assert.equal(buildPharmacyIntelligenceReport({...pharmacy,operating_hours:{mon:{open:'2200',close:'0200'}}}).peerComparison.weekdayDailyHours, 4);
assert.equal(parseNutritionFacts('일일섭취량중 500mg').length, 0);
assert.equal(getVerifiedNutritionFacts([{name:'일일섭취량중',amount:500,unit:'mg',percent_dv:null,source:'foodsafetykorea:C003'}]).length, 0);
const facts = parseNutritionFacts('1일 섭취량당: 비타민C 100mg(100%), 아연 8.5mg(100%)');
assert.equal(facts.length,2);
assert.equal(getVerifiedNutritionFacts(facts).length,2);
assert.equal(detectAdditives('원재료: 식용색소 황색 제4호').has_coloring,true);
assert.equal(detectAdditives('수크랄로스').has_artificial_sweeteners,true);
assert.equal(isSafeCrawlerQuery(new URL('https://todaypharm.kr/wiki?type=medicine&page=2')),true);
assert.equal(isSafeCrawlerQuery(new URL('https://todaypharm.kr/wiki?type=medicine&q=감기')),false);
assert.equal(getVerifiedNutritionFacts([{...facts[0], amount:999}]).length,0);
assert.equal(getVerifiedNutritionFacts([{...facts[0],unit:'unknown'}]).length,0);
assert.equal(getVerifiedNutritionFacts([{...facts[0],amount:'100'}]).length,0);
assert.equal(getVerifiedNutritionFacts([{...facts[0],name:'불명성분'}]).length,0);
assert.equal(parseNutritionFacts('1일 섭취량당 비타민C 100mg, 100g당 비타민C 1000mg').length,0);
console.log('PASS readiness: source suppression, overnight schedules, malformed nutrition, additives and crawler medicine states');
